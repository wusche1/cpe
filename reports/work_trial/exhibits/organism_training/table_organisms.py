"""Emit the organism SFT hyperparameter table as a bare tabular for \\input.

Only the settings that vary between organisms get a column; the ones held fixed
across the ladder are in data.json under "shared" and belong in the caption.
"""

import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
data = json.load(open(os.path.join(HERE, "data.json")))


def short(model_ref):
    """Shorten an imitation source to what identifies it in the ladder."""
    if model_ref == "uniform":
        return "uniform"
    if model_ref.endswith("source_logits.pt"):
        return "Qwen3.5-122B-A10B"  # cached logits of the rung below
    return model_ref.split("/")[-1]


def rows():
    for r in data["rows"]:
        yield " & ".join([
            r["model"],
            short(r["imitation_source"]),
            f"{r['learning_rate']:.1e}".replace("e-0", "e$-$"),
            f"{r['batch_size']}$\\times${r['grad_accum']}",
            str(len(r["lora_target_modules"])),
            "---" if r["max_grad_norm"] is None else f"{r['max_grad_norm']:.1f}",
        ]) + r" \\"


HEADER = "% Generated by exhibits/organism_training/table_organisms.py -- do not edit by hand.\n"

ladder = (
    "\\begin{tabular}{llrrrr}\n"
    "\\toprule\n"
    "Organism & Imitates & LR & Batch$\\times$accum. & LoRA targets & Grad. clip \\\\\n"
    "\\midrule\n"
    f"{chr(10).join(rows())}\n"
    "\\bottomrule\n"
    "\\end{tabular}\n"
)


def two_behaviour_rows():
    for r in data["two_behaviour"]:
        yield " & ".join([
            r["organism"],
            f"{r['learning_rate']:.1e}".replace("e-0", "e$-$"),
            f"{r['batch_size']}$\\times${r['grad_accum']}",
            str(r["epochs"]),
            str(r["max_seq_len"]),
        ]) + r" \\"


two_behaviour = (
    "\\begin{tabular}{lrrrr}\n"
    "\\toprule\n"
    "Organism & LR & Batch$\\times$accum. & Epochs & Seq. len. \\\\\n"
    "\\midrule\n"
    f"{chr(10).join(two_behaviour_rows())}\n"
    "\\bottomrule\n"
    "\\end{tabular}\n"
)

for name, body in (("table_organisms.tex", ladder), ("table_two_behaviour.tex", two_behaviour)):
    path = os.path.join(HERE, name)
    open(path, "w").write(HEADER + body)
    print("wrote", path)
